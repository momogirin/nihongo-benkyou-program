// Converts data/kana.json into a typed src/data/kana.ts.
// Rerun with `npm run data:build:kana` whenever data/kana.json changes.
//
// data/kana.json holds the standard 五十音図 (gojūon) plus 탁음/반탁음/요음 —
// fixed canonical reference data, nothing model-invented. Example words on the
// 청음(gojuon) rows are hand-authored common vocabulary (see data/raw/README.md).
import { readFile, writeFile } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const source = resolve(root, 'data/kana.json')
const out = resolve(root, 'src/data/kana.ts')

const kana = JSON.parse(await readFile(source, 'utf-8'))

const header = `// Generated by scripts/build-kana-data.mjs from data/kana.json — do not edit by hand.

// A single Japanese kana sound, paired across both scripts. Layout fields
// (rowKey/rowLabel/col) drive the gojūon chart grid; col is the vowel column
// (0..4 for gojuon/dakuten, 0..2 for youon), null for the standalone ん.
export type KanaGroup = 'gojuon' | 'dakuten' | 'handakuten' | 'youon'

export interface Kana {
  id: string
  hiragana: string
  katakana: string
  romaji: string
  group: KanaGroup
  rowKey: string
  rowLabel: string
  col: number | null
  // hand-authored common example word (gojuon rows only), in hiragana
  exampleJp?: string
  exampleKr?: string
}

export const kanaList: Kana[] = `

await writeFile(out, header + JSON.stringify(kana, null, 2) + '\n', 'utf-8')
console.log(`wrote ${kana.length} entries to src/data/kana.ts`)
