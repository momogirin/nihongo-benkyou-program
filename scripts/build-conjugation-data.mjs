// Converts data/conjugation.json into a typed src/data/conjugation.ts.
// Rerun with `npm run data:build:conjugation` whenever data/conjugation.json changes.
//
// The file holds curated N5/N4 verbs & adjectives (real vocabulary) tagged with
// their conjugation type. 五段/一段 classification was verified against standard
// dictionaries (帰る·入る·走る=五段, 着る=一段, etc.). The conjugated forms
// themselves are produced at runtime by src/lib/conjugation.ts (deterministic
// grammar rules), so nothing here is model-invented text.
import { readFile, writeFile } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const source = resolve(root, 'data/conjugation.json')
const out = resolve(root, 'src/data/conjugation.ts')

const entries = JSON.parse(await readFile(source, 'utf-8'))

const header = `// Generated by scripts/build-conjugation-data.mjs from data/conjugation.json — do not edit by hand.

export type ConjugationType = 'godan' | 'ichidan' | 'suru' | 'kuru' | 'iadj' | 'naadj'

// A dictionary-form verb or adjective. Its inflected forms are computed at
// runtime by src/lib/conjugation.ts from (reading/word + type).
export interface ConjugationEntry {
  id: string
  word: string
  reading: string
  meaningKr: string
  type: ConjugationType
}

export const conjugationList: ConjugationEntry[] = `

await writeFile(out, header + JSON.stringify(entries, null, 2) + '\n', 'utf-8')
const byType = entries.reduce((m, e) => ((m[e.type] = (m[e.type] || 0) + 1), m), {})
console.log(`wrote ${entries.length} entries to src/data/conjugation.ts`, byType)
