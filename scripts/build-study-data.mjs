const byId = Object.fromEntries(entries.map((e) => [e.kanjiId, e]))

await writeFile(out, header + JSON.stringify(byId, null, 2) + '\n', 'utf-8')
console.log(`wrote ${entries.length} entries to src/data/studyContent.ts (from ${files.join(', ')})`)
