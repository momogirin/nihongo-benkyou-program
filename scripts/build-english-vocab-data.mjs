// (New General Service List / TOEIC Service List, Browne & Culligan et al.,
// newgeneralservicelist.com) — see data/raw/README.md for tier design and
// license notes. pos/meaningKr/exampleEn/exampleKr are entirely model-authored
// (no source dataset has Korean glosses, part-of-speech tags, or example
// sentences per word) — same "generated, not cross-verified" caveat as
// kanji.ts's etymology/exampleKr fields and vocab.ts's meaningKr/exampleJp.

