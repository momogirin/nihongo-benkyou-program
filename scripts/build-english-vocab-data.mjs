// Converts data/english-vocab-*.json into a typed src/data/englishVocab.ts.
// Rerun with `npm run data:build:englishVocab` whenever a data/english-vocab-*.json file changes.
import { readFile, writeFile, readdir } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const dataDir = resolve(root, 'data')
const out = resolve(root, 'src/data/englishVocab.ts')

const files = (await readdir(dataDir)).filter((f) => /^english-vocab-.*\.json$/.test(f)).sort()
let entries = []
for (const file of files) {
  const chunk = JSON.parse(await readFile(resolve(dataDir, file), 'utf-8'))
  entries = entries.concat(chunk)
}

