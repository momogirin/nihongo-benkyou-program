const footer = `) as VocabWord[]\n`

const jsonStringLiteral = JSON.stringify(JSON.stringify(entries))

await writeFile(out, header + jsonStringLiteral + footer, 'utf-8')
console.log(`wrote ${entries.length} entries to src/data/vocab.ts (from ${files.join(', ')})`)
