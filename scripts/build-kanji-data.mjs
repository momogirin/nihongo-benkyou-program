// Converts data/kanji.json into a typed src/data/kanji.ts.
// Rerun with `npm run data:build` whenever data/kanji.json changes.
import { readFile, writeFile } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const source = resolve(root, 'data/kanji.json')
const out = resolve(root, 'src/data/kanji.ts')

const raw = JSON.parse(await readFile(source, 'utf-8'))

const header = `// Generated by scripts/build-kanji-data.mjs from data/kanji.json — do not edit by hand.

export type KanjiLevel = 'N5' | 'N4' | 'N3' | 'N2' | 'N1'

// where kunKr came from: hand-curated by the original spreadsheet, sourced
// from ko.wiktionary.org's 한자풀이 template (directly or via the traditional
// 구자체 form), or generated from the model's own knowledge when neither
// source had an entry (see data/raw/README.md for the generation notes)
export type KunKrSource = 'curated' | 'wiktionary' | 'wiktionary-traditional' | 'generated' | 'generated-uncertain'

export interface Kanji {
  id: string
  level: KanjiLevel
  num: number
  kanji: string
  kunKr: string
  kunJp: string
  onJp: string
  exampleKanji: string | null
  exampleKr: string | null
  exampleJp: string | null
  exampleRefKanji: string | null
  exampleRefNum: string | null
  kunKrSource: KunKrSource
}

// Parsed from a JSON string (rather than a literal array) because TS's
// literal-type checker chokes on an array-of-object-literals this large
// ("union type too complex to represent") once it has to narrow several
// string-literal-typed fields across 2000+ entries.
export const kanjiList = JSON.parse(`

const footer = `) as Kanji[]\n`

// JSON.stringify(raw) produces the JSON text; JSON.stringify of that text
// produces a complete, self-quoted, fully-escaped JS string literal — ready
// to paste as-is as the argument to JSON.parse(...) above.
const jsonStringLiteral = JSON.stringify(JSON.stringify(raw))

await writeFile(out, header + jsonStringLiteral + footer, 'utf-8')
console.log(`wrote ${raw.length} entries to src/data/kanji.ts`)
