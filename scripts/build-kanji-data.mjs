// Converts data/kanji.json into a typed src/data/kanji.ts.
// Rerun with `npm run data:build` whenever data/kanji.json changes.
import { readFile, writeFile } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const source = resolve(root, 'data/kanji.json')
const out = resolve(root, 'src/data/kanji.ts')

const raw = JSON.parse(await readFile(source, 'utf-8'))

const header = `// Generated by scripts/build-kanji-data.mjs from data/kanji.json — do not edit by hand.

export type KanjiLevel = 'N5' | 'N4' | 'N3'

export interface Kanji {
  id: string
  level: KanjiLevel
  num: number
  kanji: string
  kunKr: string
  kunJp: string
  onJp: string
  exampleKanji: string
  exampleKr: string
  exampleJp: string
  exampleRefKanji: string | null
  exampleRefNum: string | null
}

export const kanjiList: Kanji[] = `

const body = JSON.stringify(raw, null, 2)

await writeFile(out, header + body + '\n', 'utf-8')
console.log(`wrote ${raw.length} entries to src/data/kanji.ts`)
