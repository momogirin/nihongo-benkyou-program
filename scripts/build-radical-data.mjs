// Converts data/radicals.json into a typed src/data/radicals.ts.
// Rerun with `npm run data:build:radicals` whenever data/radicals.json changes.
import { readFile, writeFile } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const source = resolve(root, 'data/radicals.json')
const kanjiSource = resolve(root, 'data/kanji.json')
const out = resolve(root, 'src/data/radicals.ts')

const radicals = JSON.parse(await readFile(source, 'utf-8'))
const kanjiList = JSON.parse(await readFile(kanjiSource, 'utf-8'))
const kunKrByChar = new Map(kanjiList.map((k) => [k.kanji, k.kunKr]))

// the 214 Kangxi radical chars/stroke counts are a fixed canonical reference
// (sourced from the standard Kangxi Dictionary ordering); the Korean gloss is
// looked up from the existing verified kanji dataset where the radical is
// also a standalone jouyou kanji, so the two screens never disagree on the
// same character. The rest were cross-checked against ko.wiktionary.org
// (scripts/fetch-radical-meanings.mjs / apply-radical-meanings.mjs), except
// whichever ones had no matching entry there — those fall back to a
// hand-authored gloss that's never been cross-checked (see data/raw/README.md)
const enriched = radicals.map((r) => {
  const kanjiKunKr = kunKrByChar.get(r.radical)
  return {
    ...r,
    meaningKr: kanjiKunKr ?? r.meaningKr,
    meaningKrSource: kanjiKunKr ? 'kanji-data' : r.meaningKrSource ?? 'generated-uncertain',
  }
})

const header = `// Generated by scripts/build-radical-data.mjs from data/radicals.json — do not edit by hand.

export type RadicalMeaningSource = 'kanji-data' | 'wiktionary' | 'generated-uncertain'

export interface Radical {
  number: number
  strokeCount: number
  radical: string
  meaningEn: string
  meaningKr: string
  meaningKrSource: RadicalMeaningSource
}

export const radicalList: Radical[] = `

await writeFile(out, header + JSON.stringify(enriched, null, 2) + '\n', 'utf-8')
const generatedCount = enriched.filter((r) => r.meaningKrSource === 'generated-uncertain').length
console.log(`wrote ${enriched.length} entries to src/data/radicals.ts (${generatedCount} generated-uncertain)`)
